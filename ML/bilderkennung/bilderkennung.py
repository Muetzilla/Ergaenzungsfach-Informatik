trainingsdaten = froehliche_trainingsdaten + traurige_trainingsdaten

X = np.array([data[0] for data in trainingsdaten], dtype=float)
# WICHTIG: Konvertiere Labels zu -1 (traurig) und +1 (fröhlich)
# Statt 0 und 1, weil das Perceptron-Update mit yi * f arbeitet
y = np.array([2 * data[1] - 1 for data in trainingsdaten])  # 0 -> -1, 1 -> +1

def predict(xi, w, b):
    """Vorhersage: +1 für fröhlich, -1 für traurig"""
    f = np.dot(w, xi) + b
    return 1 if f > 0 else 0


# Startwerte - initialisiere w mit 64 Elementen für 64 Pixel
w = np.random.randn(64) * 0.01  # Kleine zufällige Werte statt Nullen
b = 0.0
alpha = 0.1  # Lernrate

durchgaenge = 10
plt.ion()
fig = plt.figure()

print("=== Trainiere Perceptron ===\n")

# Mehrere Durchgänge durch alle Datenpunkte
for durchgang in range(durchgaenge):
    errors = 0

    for i in range(len(X)):
        xi = X[i]
        yi = y[i]

        # Linear Model
        f = np.dot(w, xi) + b

        # Prüfe ob falsch klassifiziert
        if yi * f <= 0:
            # Perceptron Update-Regel mit Lernrate
            w = w + alpha * yi * xi
            b = b + alpha * yi
            errors += 1

            print(f"Durchgang {durchgang + 1}, Punkt {i}: UPDATE - yi={yi}, f={f:.3f}")
        else:
            print(f"Durchgang {durchgang + 1}, Punkt {i}: Kein Update - yi={yi}, f={f:.3f}")

    print(f"Durchgang {durchgang + 1} fertig - Fehler: {errors}\n")

    # Wenn keine Fehler mehr, konvergiert
    if errors == 0:
        print(f"✓ Konvergenz nach Durchgang {durchgang + 1}!\n")
        break

